const fs = require('fs');

const lines = [];
lines.push('// Generated static book index for Web & GitHub Pages');
lines.push('const books: Record<number, any> = {');
for (let i = 1; i <= 66; i++) {
  lines.push(`  ${i}: require('../assets/webData/book_${i}.json'),`);
}
lines.push('};');
lines.push('');
lines.push('const allBooksList = require("../assets/webData/books.json");');
lines.push('');
lines.push('export const webDb = {');
lines.push('  getAllAsync: async (query: string, params: any[] = []) => {');
lines.push('    const q = query.trim().toUpperCase();');
lines.push('    if (q.includes("FROM LIVROS")) {');
lines.push('      return allBooksList.map((b: any) => ({');
lines.push('        id: b.id,');
lines.push('        ID: b.id,');
lines.push('        nome_pt: b.nome_pt,');
lines.push('        NOME_PT: b.nome_pt,');
lines.push('        nome_en: b.nome_en,');
lines.push('        NOME_EN: b.nome_en,');
lines.push('        sigla: b.sigla,');
lines.push('        SIGLA: b.sigla,');
lines.push('      }));');
lines.push('    }');
lines.push('    if (q.includes("DISTINCT CAPITULO")) {');
lines.push('      const bookId = Number(params[0]);');
lines.push('      const book = books[bookId];');
lines.push('      if (!book || !book.chapters) return [];');
lines.push('      return book.chapters.map((c: any) => ({ CAPITULO: c.capitulo }));');
lines.push('    }');
lines.push('    if (q.includes("FROM VERSICULOS")) {');
lines.push('      const bookId = Number(params[0]);');
lines.push('      const cap = Number(params[1]);');
lines.push('      const book = books[bookId];');
lines.push('      if (!book || !book.chapters) return [];');
lines.push('      const chapter = book.chapters.find((c: any) => c.capitulo === cap);');
lines.push('      return chapter ? chapter.verses : [];');
lines.push('    }');
lines.push('    return [];');
lines.push('  },');
lines.push('  getFirstAsync: async (query: string, params: any[] = []) => {');
lines.push('    const q = query.trim().toUpperCase();');
lines.push('    if (q.includes("FROM LIVROS")) {');
lines.push('      const bookId = Number(params[0]);');
lines.push('      const book = books[bookId];');
lines.push('      if (!book) return null;');
lines.push('      return {');
lines.push('        id: book.id,');
lines.push('        ID: book.id,');
lines.push('        nome_pt: book.nome_pt,');
lines.push('        NOME_PT: book.nome_pt,');
lines.push('        nome_en: book.nome_en,');
lines.push('        NOME_EN: book.nome_en,');
lines.push('        sigla: book.sigla,');
lines.push('        SIGLA: book.sigla,');
lines.push('      };');
lines.push('    }');
lines.push('    return null;');
lines.push('  },');
lines.push('};');
lines.push('');
lines.push('export function useSQLiteContext() {');
lines.push('  return webDb;');
lines.push('}');
lines.push('');
lines.push('export function SQLiteProvider({ children }: { children: React.ReactNode }) {');
lines.push('  return children;');
lines.push('}');
lines.push('');

fs.writeFileSync('services/sqliteShim.web.ts', lines.join('\n'));
console.log('services/sqliteShim.web.ts gerado com sucesso!');
